"""Tests for the Scala generator.

The generator code is in ohi LinkML, so the tests here check mostly that the options reach it and
that the files are written where they should be.
"""

import dataclasses
import shutil
import subprocess
from pathlib import Path

import pytest
from click.testing import CliRunner

from linkml.generators.common.ohi import build_info
from linkml.generators.scalagen import ScalaGenerator, cli

ohi_linkml = pytest.importorskip("ohi_linkml", reason="ohi LinkML has no build for this platform")

pytestmark = pytest.mark.scalagen

SCHEMA = Path(__file__).parent / "input" / "scala_model.yaml"
PACKAGE = "org.example.scalamodel"

HEADER = "// Generated by ohi LinkML from https://example.org/old\n// DO NOT EDIT.\n"
OLD_HEADER = "// Generated by LinkML-Scala from https://example.org/old\n// DO NOT EDIT.\n"
"""What versions before the rename to ohi LinkML wrote. ``--clean`` has to recognize it too."""


@pytest.fixture(scope="module")
def files() -> dict[str, str]:
    """The generated files for :data:`SCHEMA`, by file name."""
    with ScalaGenerator(str(SCHEMA), package=PACKAGE) as generator:
        return generator.as_files()


@pytest.mark.parametrize(
    "name",
    [
        "NamedThing.scala",
        "Person.scala",
        "Organization.scala",
        "VitalStatus.scala",
        "AgeInYears.scala",
        "Prefixes.scala",
        # From core.yaml, which SCHEMA imports
        "Activity.scala",
    ],
)
def test_one_file_per_class_enum_and_type(files, name):
    """Classes, enums and types get a file each, imported classes included."""
    assert name in files


def test_every_file_is_in_the_package(files):
    """``--package`` reaches ohi LinkML, also for the imported classes."""
    assert all(f"\npackage {PACKAGE}\n" in code for code in files.values())


def test_default_package_is_example():
    """Without ``--package``, the package is ``example``, as in ``gen-java``."""
    assert "\npackage example\n" in ScalaGenerator(str(SCHEMA)).as_files()["Person.scala"]


def test_no_emit_prefixes_leaves_out_prefixes():
    """``--no-emit-prefixes`` becomes ohi LinkML's ``generate_emit_prefixes=False``."""
    assert "Prefixes.scala" not in ScalaGenerator(str(SCHEMA), emit_prefixes=False).as_files()


@pytest.mark.parametrize(
    "skip_leaf_interfaces,declaration",
    [(True, "final case class Person("), (False, "final case class PersonImpl(")],
)
def test_skip_leaf_interfaces(skip_leaf_interfaces, declaration):
    """A class that no other class extends is one case class, or a class and an ``...Impl``."""
    files = ScalaGenerator(str(SCHEMA), skip_leaf_interfaces=skip_leaf_interfaces).as_files()
    assert declaration in files["Person.scala"]


def test_serialize_has_every_file_after_its_name(files):
    """``serialize`` gives all files in one text, each after a ``// FILE`` comment."""
    text = ScalaGenerator(str(SCHEMA), package=PACKAGE).serialize()
    for name, code in files.items():
        assert f"// FILE {name}\n//\n{code}" in text


def test_cli_prints_every_file(files):
    """Without ``--output-directory``, the CLI prints all files."""
    result = CliRunner().invoke(cli, [str(SCHEMA), "--package", PACKAGE])
    assert result.exit_code == 0
    assert all(f"// FILE {name}\n" in result.output for name in files)


def test_cli_writes_the_files_to_the_output_directory(files, tmp_path):
    """``-d`` writes one file per class, enum and type, straight into the directory."""
    result = CliRunner().invoke(cli, [str(SCHEMA), "--package", PACKAGE, "-d", str(tmp_path / "out")])
    assert result.exit_code == 0
    assert result.output == ""
    written = {path.name: path.read_text() for path in (tmp_path / "out").iterdir()}
    assert written == files


@pytest.fixture
def leftovers(tmp_path) -> Path:
    """A directory with files from an earlier run, and files someone wrote by hand."""
    (tmp_path / "Removed.scala").write_text(HEADER + "package old\n")
    (tmp_path / "RemovedLongAgo.scala").write_text(OLD_HEADER + "package old\n")
    (tmp_path / "Handwritten.scala").write_text("package old\n" + HEADER)
    (tmp_path / "notes.txt").write_text(HEADER)
    return tmp_path


def test_clean_deletes_only_files_ohi_linkml_generated(files, leftovers):
    """``--clean`` deletes the ``.scala`` files starting with ohi LinkML's header, and keeps the rest."""
    result = CliRunner().invoke(cli, [str(SCHEMA), "-d", str(leftovers), "--clean"])
    assert result.exit_code == 0
    assert {path.name for path in leftovers.iterdir()} == set(files) | {"Handwritten.scala", "notes.txt"}


def test_without_clean_old_files_stay(files, leftovers):
    """Without ``--clean``, nothing is deleted."""
    result = CliRunner().invoke(cli, [str(SCHEMA), "-d", str(leftovers)])
    assert result.exit_code == 0
    assert {path.name for path in leftovers.iterdir()} == set(files) | {
        "Removed.scala",
        "RemovedLongAgo.scala",
        "Handwritten.scala",
        "notes.txt",
    }


def test_clean_needs_an_output_directory():
    """There is nothing to clean when the files go to stdout."""
    result = CliRunner().invoke(cli, [str(SCHEMA), "--clean"])
    assert result.exit_code == 2
    assert "--clean needs an --output-directory" in result.output


def test_every_cli_option_is_accepted_by_the_generator():
    """``cli`` hands its options straight to the constructor, so each one needs a field."""
    fields = {field.name for field in dataclasses.fields(ScalaGenerator)}
    options = {param.name for param in cli.params if param.expose_value}
    assert options - fields == {"yamlfile", "output_directory", "clean"}, (
        "yamlfile is the schema itself, and the CLI writes the files itself"
    )


def test_cli_version_reports_both_versions():
    """A bug report needs the linkml version and the ohi LinkML version, so ``-V`` shows both."""
    result = CliRunner().invoke(cli, ["-V"])
    assert result.exit_code == 0
    assert "linkml " in result.output
    assert f"ohi LinkML {build_info()['linkml_scala_version']}" in result.output


@pytest.mark.integration
@pytest.mark.skipif(shutil.which("scala-cli") is None, reason="scala-cli is not installed")
def test_generated_code_compiles(tmp_path):
    """The generated code compiles against the ohi LinkML runtime of the same version.

    Downloads the runtime from Maven Central.
    """
    info = build_info()
    ScalaGenerator(str(SCHEMA), package=PACKAGE).write(tmp_path)
    result = subprocess.run(
        [
            "scala-cli",
            "compile",
            "--server=false",
            "--scala",
            info["scala_version"],
            "--dep",
            f"eu.neverblink.linkml::runtime:{info['linkml_scala_version']}",
            str(tmp_path),
        ],
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert result.returncode == 0, result.stderr
