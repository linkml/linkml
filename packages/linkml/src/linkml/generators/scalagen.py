"""Generate Scala classes from a LinkML schema.

The translation itself is not implemented here. This module is a thin wrapper around the Scala
generator in `ohi LinkML <https://linkml.ohi.dev/>`_, using
its Python bindings. See :mod:`linkml.generators.common.ohi` for the shared machinery. Report
bugs in the output in the ohi LinkML repository.

The output is one ``.scala`` file per class, enum and type, all in one package. Classes from
imported schemas are part of it too. The generated code needs ohi LinkML's Scala runtime,
``eu.neverblink.linkml::runtime``, in the same version as the ohi LinkML that generated it.
"""

import os
from dataclasses import dataclass
from pathlib import Path
from typing import ClassVar

import click

from linkml.generators.common.ohi import OhiBackedGenerator, print_versions
from linkml.utils.generator import shared_arguments

DEFAULT_PACKAGE = "example"
"""Package used without ``--package``, the same as in ``gen-java``."""

GENERATED_HEADERS = ("// Generated by ohi LinkML from ", "// Generated by LinkML-Scala from ")
"""How the first line of a file written by ohi LinkML starts. The second is what versions before
the rename to ohi LinkML wrote. ``--clean`` deletes only the files that start with one of them."""


def is_generated_file(path: Path) -> bool:
    """Check if a file is a ``.scala`` file written by ohi LinkML, judging by its first line.

    :param path: the file to check.
    :return: whether ``--clean`` may delete it.
    """
    if path.suffix != ".scala" or not path.is_file():
        return False
    with path.open(encoding="utf-8") as stream:
        return stream.readline().startswith(GENERATED_HEADERS)


@dataclass
class ScalaGenerator(OhiBackedGenerator):
    """Generates Scala classes for the classes, enums and types of a schema, one file each.

    >>> from linkml.generators.scalagen import ScalaGenerator
    >>> schema = '''
    ... id: https://example.org/personinfo
    ... name: personinfo
    ... prefixes:
    ...   linkml: https://w3id.org/linkml/
    ...   personinfo: https://example.org/personinfo/
    ... default_prefix: personinfo
    ... default_range: string
    ... imports:
    ...   - linkml:types
    ... classes:
    ...   Person:
    ...     description: A human being
    ...     attributes:
    ...       age:
    ...         range: integer
    ... '''
    >>> files = ScalaGenerator(schema, package="org.example.personinfo").as_files()
    >>> list(files)
    ['Person.scala']
    >>> print("\\n".join(files["Person.scala"].splitlines()[:6]))
    // Generated by ohi LinkML from https://example.org/personinfo
    // DO NOT EDIT.
    <BLANKLINE>
    package org.example.personinfo
    <BLANKLINE>
    import eu.neverblink.linkml.runtime.*
    """

    generatorname: ClassVar[str] = os.path.basename(__file__)
    valid_formats: ClassVar[list[str]] = ["scala"]
    file_extension: ClassVar[str] = "scala"

    package: str = DEFAULT_PACKAGE
    """Package of the generated classes, such as ``org.example.personinfo``."""

    skip_leaf_interfaces: bool = True
    """Make a class that no other class extends one case class, instead of an abstract class and an
    ``...Impl`` case class. Turn it off when other code has to extend the generated classes."""

    emit_prefixes: bool = True
    """Generate a ``Prefixes`` object with the schema's ``emit_prefixes``.

    Becomes ohi LinkML's ``generate_emit_prefixes``.
    """

    def as_files(self) -> dict[str, str]:
        """Generate the Scala code, one file per class, enum and type.

        Lines end with ``\\n`` on every platform. ohi LinkML's Windows builds currently end some
        lines with ``\\r\\n``, so these are turned into ``\\n``.

        :return: the code of each file, by file name, sorted by file name.
        """
        files = self.ohi_schema.scala(
            generate_emit_prefixes=self.emit_prefixes,
            package=self.package,
            skip_leaf_interfaces=self.skip_leaf_interfaces,
        )
        return {name: code.replace("\r\n", "\n") for name, code in sorted(files.items())}

    def serialize(self, **kwargs) -> str:
        """Generate the Scala code as one text, each file after a ``// FILE`` comment.

        It's the same as what ohi LinkML's own CLI prints. Use :meth:`write` to get files that
        the Scala compiler can read.

        :param kwargs: ignored, so the shared CLI options can be passed straight through.
        :return: the code of all files.
        """
        return "\n".join(f"//\n// FILE {name}\n//\n{code}" for name, code in self.as_files().items())

    def write(self, directory: str | Path, clean: bool = False) -> list[Path]:
        """Write the Scala code to a directory, one file per class, enum and type.

        The files go straight into ``directory``, without a subdirectory for the package. Files
        with the same name are replaced.

        :param directory: where to write the files. Created if it does not exist.
        :param clean: delete the ``.scala`` files that ohi LinkML wrote to ``directory`` before,
            so that classes no longer in the schema do not stay behind. Files that do not start
            with ohi LinkML's header are kept.
        :return: the written files.
        """
        files = self.as_files()
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        if clean:
            for path in directory.iterdir():
                if is_generated_file(path):
                    path.unlink()
        written = []
        for name, code in files.items():
            path = directory / name
            # Written as is, so that lines end with \n on Windows too.
            path.write_text(code, encoding="utf-8", newline="\n")
            written.append(path)
        return written


@shared_arguments(ScalaGenerator)
@click.option(
    "--package",
    default=DEFAULT_PACKAGE,
    show_default=True,
    help="Package of the generated classes, such as org.example.personinfo.",
)
@click.option(
    "--skip-leaf-interfaces/--no-skip-leaf-interfaces",
    default=True,
    show_default=True,
    help="Make a class that no other class extends one case class, instead of an abstract class and an "
    "...Impl case class. Use --no-skip-leaf-interfaces when other code has to extend the "
    "generated classes.",
)
@click.option(
    "--emit-prefixes/--no-emit-prefixes",
    default=True,
    show_default=True,
    help="Generate a Prefixes object with the schema's emit_prefixes.",
)
@click.option(
    "-d",
    "--output-directory",
    type=click.Path(file_okay=False, path_type=Path),
    help="Directory to write the .scala files to. Prints all files to stdout if not given.",
)
@click.option(
    "--clean",
    is_flag=True,
    help="Before writing, delete the .scala files in the output directory that ohi LinkML "
    "generated earlier, so that classes no longer in the schema do not stay behind. Other "
    "files are kept.",
)
@click.option(
    "-V",
    "--version",
    is_flag=True,
    is_eager=True,
    expose_value=False,
    callback=print_versions,
    help="Show the linkml and ohi LinkML versions and exit.",
)
@click.command(name="scala")
def cli(yamlfile, output_directory, clean, **args):
    """Generate Scala classes from a LinkML model.

    Every class, enum and type gets its own .scala file, all in the package given by --package,
    including the ones from imported schemas. Use --output-directory to write the files, and
    --clean to remove the ones a previous run generated. The code needs the Scala runtime of ohi
    LinkML, eu.neverblink.linkml::runtime, in the version that --version shows.

    The generator is implemented in ohi LinkML, which is maintained separately. Please submit
    bug reports and feature requests to https://github.com/NeverBlink-OSS/ohi/issues
    """
    if clean and output_directory is None:
        raise click.UsageError("--clean needs an --output-directory to clean.")
    with ScalaGenerator(yamlfile, **args) as generator:
        if output_directory is None:
            print(generator.serialize())
        else:
            generator.write(output_directory, clean=clean)


if __name__ == "__main__":
    cli()
